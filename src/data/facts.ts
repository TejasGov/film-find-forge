/** Pick facts that match the group's top answers (and typed languages), shuffled. */
export function factsFor(rankings: Record<string, string[]>[]): string[] {
  const want = new Set<string>();
  for (const r of rankings) {
    for (const [qid, answers] of Object.entries(r ?? {})) {
      if (qid === "language") answers.forEach((l) => want.add(l.trim().toLowerCase()));
      else answers.slice(0, 2).forEach((a) => ANSWER_TAGS[a] && want.add(ANSWER_TAGS[a]));
    }
  }
  const hit = FACTS.filter((f) => f.tags.some((t) => want.has(t))).map((f) => f.text);
  const pool = hit.length >= 4 ? hit : [...hit, ...FACTS.filter((f) => f.tags.includes("general")).map((f) => f.text)];
  return pool.sort(() => Math.random() - 0.5);
}
